"""Per-species anatomy. Numbers are the design; exporters do not read old meshes."""

from __future__ import annotations


def spec(template, palette, pattern, body, head, limb, extras=(), muzzle=None,
         bind_body=None, direction="", wave="W2", concepts=None, silhouette=None, marks=()):
    selected = (concepts or [{"id": "primary"}])[0]["id"]
    return {
        "template": template,
        "palette_id": palette,
        "pattern": pattern,
        "body": list(body),
        "head": list(head),
        "limb": list(limb),
        "extras": list(extras),
        "muzzle": list(muzzle) if muzzle else None,
        "bind_body": list(bind_body) if bind_body else None,
        "direction": direction,
        "wave": wave,
        "silhouette": dict(silhouette or {}),
        "marks": list(marks),
        "recipe_version": 1,
        "selected_concept": selected,
        "concepts": concepts or [
            {"id": "primary", "body_scale": [1, 1, 1], "note": direction},
            {"id": "tall", "body_scale": [0.86, 1.28, 0.9], "note": "taller mass"},
            {"id": "long", "body_scale": [1.08, 0.82, 1.34], "note": "longer mass"},
        ],
    }


def _trio(a, b, c, note_a, note_b, note_c):
    return [
        {"id": a, "body_scale": [1, 1, 1], "note": note_a},
        {"id": b, "body_scale": [1.12, 0.78, 0.92], "note": note_b},
        {"id": c, "body_scale": [0.84, 1.2, 1.16], "note": note_c},
    ]


