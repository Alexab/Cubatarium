"""Verify exact item provenance, regeneration and publication after fresh Git checkouts.

Only disposable local clones are published. The working catalog and authored
sources are fingerprinted before/after; this command never promotes production.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

from itemgen.design import ROOT, build_design
from itemgen.design_publication import validate_design
from itemgen.manifest import validate_manifest


def hashes(folder):
    return {p.relative_to(folder).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(folder.rglob('*')) if p.is_file()}


CHILD = r'''
import hashlib,json,sys
from pathlib import Path
root=Path.cwd();sys.path.insert(0,str(root/'tools'))
from itemgen.design import build_design
from itemgen.design_publication import validate_design,publish_designs,_hashes
from itemgen.manifest import validate_manifest
expected=json.loads(Path(sys.argv[1]).read_text())
for name,value in expected['files'].items():
    path=(root/name).resolve()
    if not path.is_relative_to(root) or not path.is_file():raise ValueError('Missing checkout input: '+name)
    if hashlib.sha256(path.read_bytes()).hexdigest()!=value:raise ValueError('Checkout changed signed bytes: '+name)
errors=validate_manifest(root)
if errors:raise ValueError(errors)
for id in expected['ids']:
    validate_design(id,root=root)
    before=_hashes(root/'assetgen_output/items/redesign'/id)
    built=build_design(id,root=root)
    if _hashes(built)!=before:raise ValueError('Regeneration changed artifact: '+id)
    validate_design(id,root=root)
    print('Regenerated byte-identical:',id,flush=True)
references={id:_hashes(root/'models/items'/id/'_itemgen_reference')
            if (root/'models/items'/id/'_itemgen_reference').exists()
            else _hashes(root/'models/items'/id) for id in expected['ids']}
publish_designs(expected['ids'],root=root)
errors=validate_manifest(root)
if errors:raise ValueError(errors)
manifest=json.loads((root/'models/items/MANIFEST.json').read_text())
if any(manifest['items'][id].get('design_version')!=3 for id in expected['ids']):raise ValueError('Incomplete clone publication')
for id in expected['ids']:
    if _hashes(root/'models/items'/id/'_itemgen_reference')!=references[id]:raise ValueError('Archived reference changed: '+id)
    stage=root/'assetgen_output/items/redesign'/id
    for name,value in _hashes(stage).items():
        published=root/'models/items'/id/name
        if not published.is_file() or hashlib.sha256(published.read_bytes()).hexdigest()!=value:raise ValueError('Published artifact differs: '+id+'/'+name)
result=dict(passed=True,signed_files=len(expected['files']),validated_stages=len(expected['ids']),
            byte_identical_regenerated=len(expected['ids']),published_in_disposable_clone=len(expected['ids']),
            reference_archives_preserved=len(expected['ids']),published_artifacts_identical=len(expected['ids']),
            manifest_version=manifest['version'])
Path(sys.argv[2]).write_text(json.dumps(result,indent=2)+'\n',encoding='utf-8')
'''


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--skip-build',action='store_true',help='Validate and reuse all existing staged designs')
    args=parser.parse_args()
    output=ROOT/'bin/items_checkout';output.mkdir(parents=True,exist_ok=True)
    report=output/'summary.json';report.unlink(missing_ok=True)
    before_models=hashes(ROOT/'models/items');before_authors=hashes(ROOT/'tools/item_designs')
    summary=dict(passed=False,clones={},production_unchanged=False,authors_unchanged=False)
    try:
        errors=validate_manifest(ROOT)
        if errors:raise ValueError(errors)
        ids=sorted(p.parent.name for p in (ROOT/'tools/item_designs').glob('*/design.yaml'))
        catalog=sorted(p.stem for p in (ROOT/'content/items').glob('*.json'))
        if ids!=catalog:raise ValueError('Authored designs must cover the whole catalog')
        expected={};staged={}
        for id in ids:
            folder=ROOT/'assetgen_output/items/redesign'/id
            if not args.skip_build:folder=build_design(id)
            record=validate_design(id)['record'];staged[id]=folder
            for group in ('sources','definition'):
                expected.update(record[group])
            expected.update(record['generator']['sha256'])
        manifest=json.loads((ROOT/'models/items/MANIFEST.json').read_text())
        for entry in manifest['items'].values():expected.update(entry['sha256'])
        expected['models/items/MANIFEST.json']=hashlib.sha256((ROOT/'models/items/MANIFEST.json').read_bytes()).hexdigest()
        revision=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip()
        summary.update(revision=revision,item_count=len(ids),signed_files=len(expected),
                       verifier_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest())
        with tempfile.TemporaryDirectory(prefix='cubatarium-item-checkout-') as temporary:
            owned=Path(temporary).resolve()
            if owned.parent!=Path(tempfile.gettempdir()).resolve() or not owned.name.startswith('cubatarium-item-checkout-'):
                raise ValueError('Unexpected temporary checkout directory')
            input_file=owned/'expected.json'
            input_file.write_text(json.dumps(dict(ids=ids,files=expected)),encoding='utf-8')
            for mode in ('true','false'):
                clone=owned/('autocrlf-'+mode)
                child_report=output/('checkout-'+mode+'.json');child_report.unlink(missing_ok=True)
                print('Fresh checkout, core.autocrlf='+mode,flush=True)
                with (output/('checkout-'+mode+'.log')).open('w',encoding='utf-8') as log:
                    def run(command,cwd=ROOT):
                        subprocess.run([str(p) for p in command],cwd=cwd,stdout=log,stderr=subprocess.STDOUT,check=True,timeout=1200)
                    run(['git','clone','--shared','--no-checkout',ROOT,clone])
                    run(['git','config','core.autocrlf',mode],clone)
                    run(['git','sparse-checkout','init','--no-cone'],clone)
                    run(['git','sparse-checkout','set','--no-cone','/.gitattributes','/LICENSE','/tools/','/content/items/','/models/items/','/shaders/'],clone)
                    run(['git','checkout','--detach',revision],clone)
                    for id,folder in staged.items():
                        shutil.copytree(folder,clone/'assetgen_output/items/redesign'/id)
                    run([sys.executable,'-c',CHILD,input_file,child_report],clone)
                result=json.loads(child_report.read_text())
                if result.get('passed') is not True:raise ValueError('Clone verification failed: '+mode)
                summary['clones'][mode]=result
                print('Checkout mode='+mode+': passed=True',flush=True)
        summary['passed']=True
    except Exception as error:
        summary['error']=str(error)
        print(str(error),file=sys.stderr)
    finally:
        summary['production_unchanged']=hashes(ROOT/'models/items')==before_models
        summary['authors_unchanged']=hashes(ROOT/'tools/item_designs')==before_authors
        summary['passed']=summary['passed'] and summary['production_unchanged'] and summary['authors_unchanged']
        report.write_text(json.dumps(summary,indent=2)+'\n',encoding='utf-8')
    print('passed='+str(summary['passed'])+'; evidence='+str(report),flush=True)
    return 0 if summary['passed'] else 1


if __name__=='__main__':raise SystemExit(main())
